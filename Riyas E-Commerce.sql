USE IMPORTHUB;

CREATE TABLE Category
(
    Category INT PRIMARY KEY,
    CategoryName VARCHAR(50)
);

CREATE TABLE Product
(
    ProductID INT PRIMARY KEY,
    ProductName VARCHAR(100),
    Price DECIMAL(10,2),
    Stock INT,
    Category INT,
    FOREIGN KEY (Category)
    REFERENCES Category(Category)
);

